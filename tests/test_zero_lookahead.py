def test_index_disjointness_property():
    """Verify that feature indices and target indices are strictly disjoint and ordered."""
    n_days = 200
    horizon = 5
    for t in range(50, n_days - horizon):
        train_indices = list(range(0, t + 1))
        target_indices = list(range(t + 1, t + 1 + horizon))
        
        # 1. No overlapping indices
        intersection = set(train_indices).intersection(set(target_indices))
        assert len(intersection) == 0, f"Leakage detected at t={t}: {intersection}"
        
        # 2. Strict chronological sequence: max(train) < min(target)
        assert max(train_indices) < min(target_indices)
        assert min(target_indices) == max(train_indices) + 1


def test_future_perturbation_invariance():
    """Verify that mutating future returns (t+1..t+5) leaves forecast at day t completely unchanged.
    This guarantees zero data snooping or lookahead leakage.
    """
    np.random.seed(42)
    sample_returns = np.random.normal(0, 0.012, 600)
    t = 450
    
    # Baseline & GARCH computed on unperturbed series
    base_pred_orig = baseline_volatility(sample_returns[:t + 1])
    garch_pred_orig = garch_forecast_from_returns(sample_returns[:t + 1])
    
    # Now simulate a massive market crash shock on future days t+1 to t+5
    perturbed_returns = sample_returns.copy()
    perturbed_returns[t + 1 : t + 6] = [-0.08, -0.06, -0.05, -0.04, -0.03]  # -26% market shock
    
    # Recalculate predictions at day t
    base_pred_perturbed = baseline_volatility(perturbed_returns[:t + 1])
    garch_pred_perturbed = garch_forecast_from_returns(perturbed_returns[:t + 1])
    
    # Must be 100.00% identical
    assert np.isclose(base_pred_orig, base_pred_perturbed, atol=1e-12)
    assert np.isclose(garch_pred_orig, garch_pred_perturbed, atol=1e-12)
    
    # However, the realized 5-day target MUST change because it evaluates the future
    target_orig = realized_vol_5day(sample_returns, t=t, horizon=5)
    target_perturbed = realized_vol_5day(perturbed_returns, t=t, horizon=5)
    assert not np.isclose(target_orig, target_perturbed)
    assert target_perturbed > target_orig  # The crash increased realized volatility


def test_backtest_chronological_ordering():
    """Verify that predictions generated by run_backtest are in strictly ascending chronological order."""
    dates = pd.date_range("2020-01-01", periods=600, freq="B")
    np.random.seed(101)
    returns = pd.Series(np.random.normal(0, 0.01, len(dates)), index=dates)
    
    res = run_backtest(returns, min_train=300, step=5, max_points=30)
    predictions = res["predictions"]
    
    pred_dates = [p["date"] for p in predictions]
    sorted_dates = sorted(pred_dates)
    
    # Strict temporal sequence
    assert pred_dates == sorted_dates
    # No duplicate forecast dates
    assert len(pred_dates) == len(set(pred_dates))


def test_no_data_scaling_leakage():
    """Verify no global dataset-level statistics (mean, std) are used in GARCH fitting."""
    np.random.seed(777)
    # Series with low volatility initially, high volatility later
    regime1 = np.random.normal(0, 0.005, 300)  # low vol
    regime2 = np.random.normal(0, 0.030, 300)  # high vol
    full_series = np.concatenate([regime1, regime2])
    
    # Fitting GARCH at t=250 (in regime 1)
    garch_t250 = garch_forecast_from_returns(full_series[:251])
    
    # Volatility should reflect regime 1 (~8%), NOT the future high volatility in regime 2
    assert garch_t250 < 15.0, f"GARCH forecast {garch_t250}% leaked future regime 2 volatility!"


def test_real_dataset_lookahead_audit():
    """Run walk-forward backtest on real CSV data and verify target validity and metrics bounds."""
    df = data_mod.load_data("SPY")
    returns = df["Return"]
    
    # Run backtest with 25 points
    res = run_backtest(returns, min_train=504, step=5, max_points=25)
    
    assert res["n_points"] == 25
    assert "baseline" in res and "garch" in res
    assert res["baseline"]["MAE"] > 0
    assert res["garch"]["MAE"] > 0
    assert res["baseline"]["RMSE"] > 0
    assert res["garch"]["RMSE"] > 0
    
    for row in res["predictions"]:
        assert row["baseline"] > 0
        assert row["garch"] > 0
        assert row["actual"] > 0
        # Check reasonable equity market bounds (1% to 150%)
        assert 1.0 <= row["baseline"] <= 150.0
        assert 1.0 <= row["garch"] <= 150.0
        assert 1.0 <= row["actual"] <= 150.0
